const APPLY = process.argv.includes("--apply");

async function main() {
  console.log(`mode: ${APPLY ? "APPLY（本番更新）" : "DRY-RUN（書き込みなし）"}  対象エントリ ${ENTRIES.length}件\n`);
  let updatedRows = 0;
  let alreadySet = 0;
  const unmatched: Entry[] = [];

  for (const e of ENTRIES) {
    const where = {
      name: e.name, setName: e.setName, deletedAt: null,
      ...(e.rarity ? { rarity: e.rarity } : {}),
    };
    const cards = await prisma.card.findMany({ where, select: { id: true, cardNumber: true } });
    if (cards.length === 0) { unmatched.push(e); continue; }
    const targets = cards.filter((c) => c.cardNumber !== e.cardNumber);
    alreadySet += cards.length - targets.length;
    if (targets.length === 0) continue;
    if (APPLY) {
      await prisma.card.updateMany({
        where: { id: { in: targets.map((c) => c.id) } },
        data:  { cardNumber: e.cardNumber },
      });
    }
    updatedRows += targets.length;
  }

  console.log(`結果: 更新${APPLY ? "" : "予定"} ${updatedRows}行 / 設定済みスキップ ${alreadySet}行 / DB未登録のエントリ ${unmatched.length}件`);
  if (unmatched.length > 0) {
    console.log("\n--- DB に該当カードが無いエントリ（未追加カード、または名前の表記ゆれ） ---");
    for (const u of unmatched) console.log(`  [${u.setName}] ${u.name} ${u.rarity ?? ""} → ${u.cardNumber}`);
  }
}

main()
  .catch((e) => { console.error(e); process.exitCode = 1; })
  .finally(() => prisma.$disconnect());
