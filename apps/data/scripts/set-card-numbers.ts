/**
 * set-card-numbers.ts — 公式カード番号を Card.cardNumber に投入（恒久運用スクリプト）
 *
 * 使い方（apps/data から実行）:
 *   node --env-file=.env.local --import tsx scripts/set-card-numbers.ts           # DRY-RUN
 *   node --env-file=.env.local --import tsx scripts/set-card-numbers.ts --apply   # 実際に更新
 *
 * 仕様:
 *   - name + setName（+ rarity 指定時は rarity）で一致する全カード（NM/PSA10 等すべての
 *     コンディション）に同じ番号を設定する
 *   - 既に同じ番号が入っている行は更新しない（冪等）
 *   - 一致しなかったエントリは最後に一覧表示する（名前の表記ゆれ確認用）
 *
 * 収録方針: 公式サイト・大手相場サイトで番号を確認できたカードのみ。確証が弱いもの
 * （単一ソースの番号、同名同レアリティで番号が2種あるカード）は入れない。
 * 誤った番号は、正しい番号入りの出品を照合で弾いてしまうため。
 */

import { prisma } from "@gci/db";

type Entry = { setName: string; name: string; rarity: string | null; cardNumber: string };
const ENTRIES: Entry[] = [];

/** ポケカ: 番号 "113" と分母 "/076" から "113/076" を作る */
function pk(setName: string, denom: string, rows: [string, string, string][]) {
  for (const [name, rarity, num] of rows) ENTRIES.push({ setName, name, rarity, cardNumber: `${num}/${denom}` });
}
/** ワンピ・遊戯王: 番号をそのまま使う。rarity が null ならセット内の同名カード全体に適用 */
function raw(setName: string, rows: [string, string | null, string][]) {
  for (const [name, rarity, num] of rows) ENTRIES.push({ setName, name, rarity, cardNumber: num });
}

